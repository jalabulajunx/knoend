#!/usr/bin/env python3
"""Turn the icons named in spec/icons.txt into LVGL images for the firmware.

Reads Google's Material Icons font (Apache-2.0; download MaterialIcons-Regular.ttf and
MaterialIcons-Regular.codepoints from github.com/google/material-design-icons/tree/master/font)
and writes firmware/components/icons/: one 4-bit alpha image per icon (the board colours it),
looked up by name. Needs Pillow.

    python3 tools/build_icons.py path/to/font-folder
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SIZE = 32
OUT = ROOT / "firmware" / "components" / "icons"


def names() -> list[str]:
    lines = (ROOT / "spec" / "icons.txt").read_text().splitlines()
    return [l.strip() for l in lines if l.strip() and not l.startswith("#")]


def render(font: ImageFont.FreeTypeFont, codepoint: int) -> bytes:
    image = Image.new("L", (SIZE, SIZE), 0)
    ImageDraw.Draw(image).text((SIZE // 2, SIZE // 2), chr(codepoint), font=font, fill=255, anchor="mm")
    pixels = image.load()
    out = bytearray()
    for y in range(SIZE):
        for x in range(0, SIZE, 2):  # two pixels per byte, high nibble first
            out.append(((pixels[x, y] >> 4) << 4) | (pixels[x + 1, y] >> 4))
    return bytes(out)


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    folder = Path(sys.argv[1])
    codepoints = dict(line.split() for line in (folder / "MaterialIcons-Regular.codepoints").read_text().splitlines() if line.strip())
    font = ImageFont.truetype(str(folder / "MaterialIcons-Regular.ttf"), SIZE)
    wanted = names()
    missing = [n for n in wanted if n not in codepoints]
    if missing:
        print(f"not in the font: {', '.join(missing)}")
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    c = ["// Generated by tools/build_icons.py from Google's Material Icons (Apache-2.0, see LICENSE).",
         "// Do not edit: change spec/icons.txt and run the script again.", "",
         '#include <string.h>', '#include "icons.h"', ""]
    for name in wanted:
        data = render(font, int(codepoints[name], 16))
        c.append(f"static const uint8_t {name}_map[] = {{")
        for i in range(0, len(data), 16):
            c.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        c.append("};")
        c.append(f"static const lv_img_dsc_t {name}_img = {{ .header = {{ .cf = LV_IMG_CF_ALPHA_4BIT, .w = {SIZE}, .h = {SIZE} }}, "
                 f".data_size = sizeof({name}_map), .data = {name}_map }};")
    c.append("")
    c.append("static const struct { const char *name; const lv_img_dsc_t *img; } ICONS[] = {")
    for name in wanted:
        c.append(f'    {{ "{name}", &{name}_img }},')
    c.append("};")
    c.append("")
    c.append("const lv_img_dsc_t *icons_find(const char *name)")
    c.append("{")
    c.append("    if (name == NULL || name[0] == '\\0') {")
    c.append("        return NULL;")
    c.append("    }")
    c.append("    for (size_t i = 0; i < sizeof(ICONS) / sizeof(ICONS[0]); i++) {")
    c.append("        if (strcmp(ICONS[i].name, name) == 0) {")
    c.append("            return ICONS[i].img;")
    c.append("        }")
    c.append("    }")
    c.append("    return NULL;")
    c.append("}")
    (OUT / "icons.c").write_text("\n".join(c) + "\n")
    (OUT / "icons.h").write_text("""// Material Icons for keys (Apache-2.0, see LICENSE), by the names in spec/icons.txt.
#pragma once

#include "lvgl.h"

#define ICONS_SIZE 32

// The icon called `name` (a 4-bit alpha image: draw it with img_recolor), or NULL.
const lv_img_dsc_t *icons_find(const char *name);
""")
    (OUT / "CMakeLists.txt").write_text('idf_component_register(SRCS "icons.c" INCLUDE_DIRS "." REQUIRES lvgl)\n')
    (OUT / "LICENSE").write_text((folder / "LICENSE").read_text())
    (OUT / "NOTICE").write_text("The icons in icons.c are rendered from Material Icons by Google "
                                "(https://github.com/google/material-design-icons), licensed under the "
                                "Apache License 2.0 (LICENSE in this folder). Changes: rasterised at 32x32 "
                                "pixels as 4-bit alpha by tools/build_icons.py.\n")
    print(f"{len(wanted)} icons -> {OUT.relative_to(ROOT)} ({len(wanted) * SIZE * SIZE // 2 // 1024} KB of pixels)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
